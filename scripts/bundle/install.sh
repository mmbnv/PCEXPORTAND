#!/usr/bin/env bash
# PortAgent bundle installer (Linux/macOS).
#
#   ./install.sh
#
# Makes this folder self-contained: it points PortAgent at the tools/ that ship
# inside the bundle and writes env.sh you can `source` (START.sh does it for
# you).  Nothing is installed system-wide and no network access is required.
set -u

BUNDLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TOOLS="$BUNDLE_DIR/tools"

say() { printf '\033[36m[install]\033[0m %s\n' "$*"; }
warn() { printf '\033[33m[install] WARN:\033[0m %s\n' "$*" >&2; }

say "bundle directory: $BUNDLE_DIR"

# --- Python ------------------------------------------------------------------
PY=""
for c in python3 python; do
    if command -v "$c" >/dev/null 2>&1; then PY="$c"; break; fi
done
if [ -z "$PY" ]; then
    warn "python3 not found. Install Python 3.10+ and re-run."
    exit 1
fi
say "python: $($PY --version 2>&1)"

# --- locate the NDK version present in the bundle ----------------------------
NDK_DIR=""
if [ -d "$TOOLS/android-sdk/ndk" ]; then
    NDK_DIR="$(find "$TOOLS/android-sdk/ndk" -maxdepth 1 -mindepth 1 -type d | sort | tail -1)"
fi

# --- write env.sh ------------------------------------------------------------
{
    echo "# Generated by install.sh -- source this before using PortAgent."
    echo "export PAGENT_TOOLS_HOME=\"$TOOLS\""
    echo "export ANDROID_HOME=\"$TOOLS/android-sdk\""
    echo "export ANDROID_SDK_ROOT=\"\$ANDROID_HOME\""
    [ -n "$NDK_DIR" ] && echo "export ANDROID_NDK_HOME=\"$NDK_DIR\""
    echo "export PATH=\"\$PAGENT_TOOLS_HOME/jadx/bin:\$PATH\""
    echo "export PYTHONPATH=\"$BUNDLE_DIR:\$PYTHONPATH\""
} > "$BUNDLE_DIR/env.sh"
say "wrote env.sh"

# --- verify what is present --------------------------------------------------
echo
say "checking bundled tools:"
check() {  # check <label> <path>
    if [ -e "$2" ]; then printf '  \033[32mOK\033[0m   %s\n' "$1";
    else printf '  \033[33mMISS\033[0m %s\n' "$1"; fi
}
check "Android SDK (aapt2/d8/zipalign/apksigner)" "$TOOLS/android-sdk/build-tools"
check "Android platform android.jar"             "$TOOLS/android-sdk/platforms"
check "Android NDK (clang for libportagent.so)"  "$TOOLS/android-sdk/ndk"
check "jadx (dex -> java)"                        "$TOOLS/jadx"
check "Il2CppDumper"                              "$TOOLS/il2cppdumper"
check "Wine/Box64/DXVK runtime (~475 MB)"         "$TOOLS/runtime/wine_dxvk"

echo
say "installation complete."
say "start the app with:  ./START.sh"
